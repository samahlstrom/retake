// migrations are the server store's schema on SQLite, one forward-only step per version (spec/server.md,
// "Storage drivers"). Never edit or reorder a step that shipped; append a new one, to both lists.
var migrations = []string{
	// 1: projects, users, members, sign-in links, sessions and settings.
	`
CREATE TABLE projects (
	id      INTEGER PRIMARY KEY AUTOINCREMENT,
	name    TEXT NOT NULL UNIQUE,                  -- the /p/<name>/ address
	title   TEXT NOT NULL DEFAULT '',
	created TEXT NOT NULL
);

CREATE TABLE users (
	id       INTEGER PRIMARY KEY AUTOINCREMENT,
	email    TEXT NOT NULL UNIQUE,                 -- lower case
	name     TEXT NOT NULL DEFAULT '',
	admin    INTEGER NOT NULL DEFAULT 0,
	created  TEXT NOT NULL,
	disabled TEXT NOT NULL DEFAULT ''              -- '' = not disabled, else when
);

CREATE TABLE members (
	project_id INTEGER NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
	user_id    INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	role       TEXT NOT NULL CHECK (role IN ('viewer', 'reviewer', 'approver', 'owner')),
	created    TEXT NOT NULL,
	PRIMARY KEY (project_id, user_id)
);
CREATE INDEX members_user ON members (user_id);

CREATE TABLE signin_links (
	hash    TEXT PRIMARY KEY,                      -- SHA-256 of the code, hex
	user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	created TEXT NOT NULL,
	expires TEXT NOT NULL,
	used    TEXT NOT NULL DEFAULT ''               -- '' = unused, else when
);

CREATE TABLE sessions (
	id         INTEGER PRIMARY KEY AUTOINCREMENT,
	hash       TEXT NOT NULL UNIQUE,               -- SHA-256 of the cookie's value, hex
	prev_hash  TEXT NOT NULL DEFAULT '',           -- the value before the last rotation, valid until prev_until
	prev_until TEXT NOT NULL DEFAULT '',
	user_id    INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	created    TEXT NOT NULL,
	rotated    TEXT NOT NULL,
	seen       TEXT NOT NULL,                      -- last use, written at most once a minute
	expires    TEXT NOT NULL,                      -- the absolute end
	revoked    TEXT NOT NULL DEFAULT '',
	agent      TEXT NOT NULL DEFAULT '',           -- the browser's User-Agent, for the session list
	ip         TEXT NOT NULL DEFAULT ''
);
CREATE INDEX sessions_prev ON sessions (prev_hash);
CREATE INDEX sessions_user ON sessions (user_id);

CREATE TABLE settings (
	key   TEXT PRIMARY KEY,
	value TEXT NOT NULL
);
`,
	// 2: machine tokens (spec/server.md, "Machines").
	`
CREATE TABLE machine_tokens (
	id         INTEGER PRIMARY KEY AUTOINCREMENT,
	hash       TEXT NOT NULL UNIQUE,               -- SHA-256 of the token, hex
	created_by INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	created    TEXT NOT NULL,
	used       TEXT NOT NULL DEFAULT '',           -- last use, written at most once a minute
	revoked    TEXT NOT NULL DEFAULT ''            -- '' = not revoked, else when
);
`,
	// 3: where a connected computer's project is in its folder (spec/home.md, the home's tree).
	`
ALTER TABLE projects ADD COLUMN path TEXT NOT NULL DEFAULT '';          -- the video's folder, relative
ALTER TABLE projects ADD COLUMN project_path TEXT NOT NULL DEFAULT '';  -- its project's folder, relative
`,
}

