//! `retake-edit component preview` (spec/components.md, "Previews"): every example of a component rendered at five
//! moments into a storybook sheet (PNG), plus a 2-second, 10 fps animated WebP of the first example. Footage and
//! image inputs get generated placeholders, so a component can be seen before it is used.

use crate::engine::{Engine, Options};
use crate::expr::Js;
use crate::ffmpeg::ffmpeg_bin;
use crate::graphics::{DISPLAY_FONT, DISPLAY_WEIGHT, FontData, Painter, Resources};
use crate::store::hex_of;
use crate::unit::{Graphics, compose};
use anyhow::{Context, Result, anyhow, bail};
use retake_timeline::component::{self, Lock, LockEntry, LockMode, Package};
use retake_timeline::layer::parse_layer;
use retake_timeline::{Errors, Project};
use serde::Serialize;
use serde_json::{Value, json};
use skia_safe::{AlphaType, Color4f, ColorType, Data, ISize, ImageInfo, Paint, Rect, images, surfaces};
use std::collections::{BTreeMap, BTreeSet};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::Arc;

/// Tile width in the sheet; the height follows the component's canvas.
pub const TILE_W: u32 = 320;
/// The fractions of an example's duration the sheet shows: the entrance, settled, and the exit.
pub const MOMENTS: [f64; 5] = [0.04, 0.12, 0.35, 0.7, 0.95];
const FPS: u32 = 30;
const WEBP_FPS: u32 = 10;
const WEBP_SECONDS: f64 = 2.0;

#[derive(Debug, Clone, Serialize)]
pub struct PreviewReport {
    pub component: String,
    pub hash: String,
    pub sheet: PathBuf,
    pub sheet_bytes: u64,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub webp: Option<PathBuf>,
    pub examples: Vec<ExampleShot>,
    pub seconds: f64,
}

#[derive(Debug, Clone, Serialize)]
pub struct ExampleShot {
    pub name: String,
    pub duration: f64,
    /// The moments shown, in seconds.
    pub times: Vec<f64>,
}

#[derive(Debug, Clone)]
pub struct PreviewOptions {
    /// Where `sheet.png` and `preview.webp` go (default `<component>/previews`).
    pub out: Option<PathBuf>,
    /// Also make the animated WebP.
    pub webp: bool,
    /// Scratch folder (default: a temporary folder, removed after).
    pub work: Option<PathBuf>,
}

impl Default for PreviewOptions {
    fn default() -> Self {
        PreviewOptions { out: None, webp: true, work: None }
    }
}

fn even(x: f64) -> u32 {
    ((x / 2.0).round() as u32 * 2).max(2)
}

/// A 16-bit mono silent WAV.
fn write_silence(path: &Path, seconds: f64) -> Result<()> {
    let sr = 48000u32;
    let n = (seconds * sr as f64).ceil() as u32;
    let data = n * 2;
    let mut b: Vec<u8> = Vec::with_capacity(44 + data as usize);
    b.extend_from_slice(b"RIFF");
    b.extend_from_slice(&(36 + data).to_le_bytes());
    b.extend_from_slice(b"WAVEfmt ");
    b.extend_from_slice(&16u32.to_le_bytes());
    b.extend_from_slice(&1u16.to_le_bytes());
    b.extend_from_slice(&1u16.to_le_bytes());
    b.extend_from_slice(&sr.to_le_bytes());
    b.extend_from_slice(&(sr * 2).to_le_bytes());
    b.extend_from_slice(&2u16.to_le_bytes());
    b.extend_from_slice(&16u16.to_le_bytes());
    b.extend_from_slice(b"data");
    b.extend_from_slice(&data.to_le_bytes());
    b.resize(44 + data as usize, 0);
    std::fs::write(path, b).with_context(|| format!("writing {}", path.display()))
}

/// Placeholder footage: a slow gradient with a grid and a moving square (so zooms, freezes and picture-in-picture
/// read), generated by ffmpeg. Deterministic for a given ffmpeg build.
fn write_footage(path: &Path, seconds: f64) -> Result<()> {
    let src = "gradients=s=640x360:c0=0x2f3f66:c1=0x5f4677:c2=0x2b625e:n=3:speed=0.012:seed=7:r=30,\
               drawgrid=w=64:h=64:t=1:c=white@0.16,drawbox=x=296:y=156:w=48:h=48:color=white@0.55:t=3[bg];\
               color=c=0xffd23f:s=56x56:r=30[sq];[bg][sq]overlay=x='70+150*t':y=152:shortest=1[out0]";
    let st = Command::new(ffmpeg_bin())
        .args(["-nostdin", "-v", "error", "-y", "-f", "lavfi", "-i", src, "-t"])
        .arg(format!("{seconds:.3}"))
        .args([
            "-c:v",
            "libx264",
            "-preset",
            "veryfast",
            "-crf",
            "24",
            "-g",
            "15",
            "-pix_fmt",
            "yuv420p",
            "-threads",
            "1",
            "-fflags",
            "+bitexact",
            "-flags:v",
            "+bitexact",
            "-an",
        ])
        .arg(path)
        .status()
        .context("running ffmpeg for placeholder footage")?;
    if !st.success() {
        bail!("ffmpeg couldn't make placeholder footage");
    }
    Ok(())
}

/// Placeholder image: a gray checkerboard.
fn write_image(path: &Path) -> Result<()> {
    let (w, h) = (480u32, 360u32);
    let mut px = vec![0u8; (w * h * 4) as usize];
    for y in 0..h {
        for x in 0..w {
            let on = ((x / 40) + (y / 40)) % 2 == 0;
            let v = if on { 196 } else { 128 };
            let i = ((y * w + x) * 4) as usize;
            px[i..i + 4].copy_from_slice(&[v, v, v, 255]);
        }
    }
    std::fs::write(path, crate::graphics::png(&px, w, h).map_err(|e| anyhow!(e))?)?;
    Ok(())
}

/// The preview timeline of one example: the component as an overlay over a soft backdrop, or as the picture.
fn example_timeline(pkg: &Package, props: &Value, dur: f64, inputs: &BTreeMap<String, String>) -> Value {
    let c = &pkg.comp;
    let [w, h] = c.canvas();
    let mut assets = json!({"proj:silence": {"path": "silence.wav"}});
    for (id, file) in inputs {
        assets[id] = json!({"path": file});
    }
    let reference = c.reference();
    let as_overlay = c.use_as.iter().any(|u| u == "overlay");
    let (wf, hf) = (w as f64, h as f64);
    let backdrop = json!({"id": "backdrop", "at": "t:0", "picture": {"background": "#262a33", "layers": [
        {"id": "backdrop/a", "type": "shape", "shape": "ellipse", "size": [wf * 0.9, hf * 1.1], "fill": "#465270",
         "blur": wf * 0.08, "transform": {"position": [wf * 0.25, hf * 0.3]}},
        {"id": "backdrop/b", "type": "shape", "shape": "ellipse", "size": [wf * 0.8, hf], "fill": "#2f5753",
         "blur": wf * 0.08, "transform": {"position": [wf * 0.8, hf * 0.8]}}
    ]}});
    let (shots, overlays) = if as_overlay {
        (
            json!([backdrop]),
            json!([{"id": "example", "use": reference, "from": "t:0", "to": format!("t:{dur:.3}"), "props": props}]),
        )
    } else {
        (json!([{"id": "example", "at": "t:0", "picture": {"use": reference, "props": props}}]), json!([]))
    };
    json!({
        "schema": "timeline/0.1", "id": "preview", "rev": 0,
        "format": {"size": [w, h], "fps": FPS, "sample_rate": 48000, "background": "#22252c"},
        "assets": assets,
        "spine": [{"id": "silence", "asset": "proj:silence", "in": 0, "dur": dur}],
        "scenes": [{"id": "preview", "shots": shots, "overlays": overlays}]
    })
}

/// Renders the frames at `want` (output frame numbers) of a preview project, at `scale`.
fn frames(project: Project, scale: f64, cache: &Path, want: &BTreeSet<i64>) -> Result<BTreeMap<i64, Vec<u8>>> {
    let e = Engine::from_project(
        project,
        Options { scale: Some(scale), jobs: 1, cache: Some(cache.into()), ..Options::default() },
    )?;
    let mut out = BTreeMap::new();
    let mut js = Js::new().map_err(|x| anyhow!(x))?;
    for plan in e.plan()? {
        let (f0, f1) = (plan.span.f0, plan.span.f1);
        let last = match want.range(f0..f1).next_back() {
            Some(l) => *l,
            None => continue,
        };
        let faces = e.resources.faces(plan.runs.iter().flat_map(|r| r.layers.iter()));
        let mut painter = Painter::new(e.resources.clone(), &faces).map_err(|x| anyhow!(x))?;
        let mut i = f0;
        compose(&plan, 0, last - f0 + 1, Graphics::Live(&mut painter, &plan.runs), &mut js, |fr| {
            if want.contains(&i) {
                out.insert(i, fr.px.clone());
            }
            i += 1;
            Ok(())
        })?;
    }
    Ok(out)
}

fn label_painter() -> Result<Painter> {
    let mut res = Resources::default();
    res.fonts.insert(
        "display".into(),
        FontData { bytes: Arc::new(DISPLAY_FONT.to_vec()), hash: hex_of(DISPLAY_FONT), weight: DISPLAY_WEIGHT },
    );
    let faces: BTreeSet<(String, u32)> = [500u32, 700, 800].iter().map(|w| ("display".to_string(), *w)).collect();
    Painter::new(Arc::new(res), &faces).map_err(|x| anyhow!(x))
}

/// Text drawn onto the sheet: (size, weight, fill).
type Style<'a> = (f64, u32, &'a str);

fn label(p: &mut Painter, canvas: &skia_safe::Canvas, text: &str, xy: (f64, f64), style: Style) -> Result<()> {
    let (size, weight, fill) = style;
    let l = parse_layer(&json!({"id": "label", "type": "text", "text": text, "size": size, "weight": weight,
        "fill": fill, "align": "left", "line_height": 1.0, "transform": {"anchor": [0, 0.5], "position": [xy.0, xy.1]}}))
    .map_err(|e| anyhow!(e))?;
    // The comp size only matters for layers without a position; labels always have one.
    p.draw_layer(canvas, &l, 0.0, &json!({}), (1.0, 1.0)).map_err(|x| anyhow!(x))
}

/// One example's row in the sheet: its name, description, duration and the tiles (time, pixels).
struct Row {
    name: String,
    desc: Option<String>,
    dur: f64,
    tiles: Vec<(f64, Vec<u8>)>,
}

fn fmt_t(t: f64) -> String {
    format!("{t:.2} s")
}

/// Renders a component's previews.
pub fn preview(dir: &Path, opts: &PreviewOptions) -> Result<PreviewReport> {
    let started = std::time::Instant::now();
    crate::init();
    let pkg = component::load_component(dir)?;
    let c = pkg.comp.clone();
    if c.examples.is_empty() {
        bail!(
            retake_timeline::EditError::new("component_no_examples", format!("{} has no examples", c.reference()))
                .hint("add at least one {name, props} to \"examples\"")
        );
    }
    let tmp_owned;
    let work = match &opts.work {
        Some(w) => w.clone(),
        None => {
            tmp_owned = std::env::temp_dir().join(format!("retake-preview-{}-{}", c.name, std::process::id()));
            tmp_owned.clone()
        }
    };
    std::fs::create_dir_all(&work)?;
    let result = (|| -> Result<PreviewReport> {
        let [cw, ch] = c.canvas();
        let scale = TILE_W as f64 / cw as f64;
        let (tw, th) = (even(cw as f64 * scale), even(ch as f64 * scale));
        // Placeholders for asset inputs.
        let max_dur = c.examples.iter().map(|e| e.duration.or(c.duration).unwrap_or(3.0)).fold(WEBP_SECONDS, f64::max);
        write_silence(&work.join("silence.wav"), max_dur + 1.0)?;
        let mut made: BTreeSet<&str> = BTreeSet::new();
        // A lock that pins this package, and its parent folder as the only search root.
        let mut lock = Lock::default();
        lock.packages.insert(
            c.reference(),
            LockEntry { kind: "component".into(), hash: pkg.hash.clone(), ..LockEntry::default() },
        );
        let roots = vec![pkg.dir.parent().map(Path::to_path_buf).unwrap_or_else(|| PathBuf::from("."))];
        let defaults = c.defaults();
        let mut rows: Vec<Row> = vec![];
        let mut webp_frames: Vec<Vec<u8>> = vec![];
        let mut shots = vec![];
        for (i, ex) in c.examples.iter().enumerate() {
            let dur = ex.duration.or(c.duration).unwrap_or(3.0);
            let mut inputs = BTreeMap::new();
            for (prop, kind) in c.asset_inputs() {
                let id = ex.props.get(&prop).or_else(|| defaults.get(&prop)).and_then(Value::as_str);
                let Some(id) = id else { continue };
                let file = match kind.as_str() {
                    "image" => "placeholder.png",
                    _ => "placeholder.mp4",
                };
                if made.insert(file) {
                    if file.ends_with(".png") {
                        write_image(&work.join(file))?;
                    } else {
                        write_footage(&work.join(file), max_dur + 1.0)?;
                    }
                }
                inputs.insert(id.to_string(), file.to_string());
            }
            let tl = example_timeline(&pkg, &ex.props, dur, &inputs);
            let path = work.join(format!("example-{i}.json"));
            let project = Project::open_in(&path, tl, LockMode::Strict, Some(lock.clone()), roots.clone())
                .map_err(|e: Errors| anyhow!(e).context(format!("example \"{}\"", ex.name)))?;
            let times: Vec<f64> = MOMENTS.iter().map(|m| m * dur).collect();
            let mut want: BTreeSet<i64> = times.iter().map(|t| (t * FPS as f64).round() as i64).collect();
            let webp_idx: Vec<i64> = if i == 0 && opts.webp {
                let n = ((dur.min(WEBP_SECONDS)) * WEBP_FPS as f64).round() as i64;
                (0..n).map(|k| k * (FPS / WEBP_FPS) as i64).collect()
            } else {
                vec![]
            };
            want.extend(webp_idx.iter().copied());
            let got = frames(project, scale, &work.join("cache"), &want)
                .with_context(|| format!("example \"{}\"", ex.name))?;
            let tiles: Vec<(f64, Vec<u8>)> = times
                .iter()
                .map(|t| {
                    let f = (t * FPS as f64).round() as i64;
                    (*t, got.get(&f).cloned().unwrap_or_else(|| vec![0; (tw * th * 4) as usize]))
                })
                .collect();
            webp_frames.extend(webp_idx.iter().filter_map(|f| got.get(f).cloned()));
            rows.push(Row { name: ex.name.clone(), desc: ex.description.clone(), dur, tiles });
            shots.push(ExampleShot { name: ex.name.clone(), duration: dur, times });
        }
        // The sheet.
        let (pad, gap, header, row_label) = (16u32, 8u32, 70u32, 30u32);
        let sw = pad * 2 + 5 * tw + 4 * gap;
        let sh = header + rows.len() as u32 * (row_label + th + pad) + pad / 2;
        let info = ImageInfo::new(ISize::new(sw as i32, sh as i32), ColorType::RGBA8888, AlphaType::Premul, None);
        let mut surface = surfaces::raster(&info, None, None).ok_or_else(|| anyhow!("can't make the sheet"))?;
        let mut lp = label_painter()?;
        {
            let canvas = surface.canvas();
            canvas.clear(Color4f::new(0.075, 0.082, 0.098, 1.0));
            label(&mut lp, canvas, &c.reference(), (pad as f64, 24.0), (24.0, 800, "#f2f2ee"))?;
            let sub = match &c.category {
                Some(cat) => format!("{} · {cat} · {}", c.title, c.use_as.join(", ")),
                None => format!("{} · {}", c.title, c.use_as.join(", ")),
            };
            label(&mut lp, canvas, &sub, (pad as f64, 52.0), (17.0, 500, "#9aa0aa"))?;
            for (r, Row { name, desc, dur, tiles }) in rows.iter().enumerate() {
                let y0 = header + r as u32 * (row_label + th + pad);
                let mut head = format!("{name}  ({:.1} s)", dur);
                if let Some(d) = desc {
                    head = format!("{head}  {d}");
                }
                label(&mut lp, canvas, &head, (pad as f64, y0 as f64 + 13.0), (16.0, 700, "#dcdcd6"))?;
                for (k, (t, px)) in tiles.iter().enumerate() {
                    let x = pad + k as u32 * (tw + gap);
                    let y = y0 + row_label;
                    let ti =
                        ImageInfo::new(ISize::new(tw as i32, th as i32), ColorType::RGBA8888, AlphaType::Premul, None);
                    let img = images::raster_from_data(&ti, Data::new_copy(px), (tw * 4) as usize)
                        .ok_or_else(|| anyhow!("can't wrap a tile"))?;
                    canvas.draw_image(&img, (x as f32, y as f32), None);
                    // The time, top right: graphics sit lower and left more often.
                    let mut pill = Paint::new(Color4f::new(0.0, 0.0, 0.0, 0.62), None);
                    pill.set_anti_alias(true);
                    let px0 = (x + tw) as f32 - 62.0;
                    canvas.draw_round_rect(Rect::from_xywh(px0, y as f32 + 6.0, 56.0, 20.0), 6.0, 6.0, &pill);
                    let at = (px0 as f64 + 7.0, y as f64 + 16.0);
                    label(&mut lp, canvas, &fmt_t(*t), at, (13.0, 700, "#ffffff"))?;
                }
            }
        }
        let mut px = vec![0u8; (sw * sh * 4) as usize];
        if !surface.read_pixels(&info, &mut px, (sw * 4) as usize, (0, 0)) {
            bail!("reading the sheet back failed");
        }
        let out = opts.out.clone().unwrap_or_else(|| pkg.dir.join("previews"));
        std::fs::create_dir_all(&out)?;
        let sheet = out.join("sheet.png");
        std::fs::write(&sheet, crate::graphics::png(&px, sw, sh).map_err(|e| anyhow!(e))?)?;
        let webp = if opts.webp && !webp_frames.is_empty() {
            let p = out.join("preview.webp");
            encode_webp(&webp_frames, tw, th, &p)?;
            Some(p)
        } else {
            None
        };
        Ok(PreviewReport {
            component: c.reference(),
            hash: pkg.hash.clone(),
            sheet_bytes: std::fs::metadata(&sheet)?.len(),
            sheet,
            webp,
            examples: shots,
            seconds: (started.elapsed().as_secs_f64() * 100.0).round() / 100.0,
        })
    })();
    if opts.work.is_none() {
        let _ = std::fs::remove_dir_all(&work);
    }
    result
}

/// Encodes RGBA frames as a looping animated WebP at 10 fps with ffmpeg's libwebp.
fn encode_webp(frames: &[Vec<u8>], w: u32, h: u32, out: &Path) -> Result<()> {
    let mut child = Command::new(ffmpeg_bin())
        .args(["-nostdin", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgba", "-s"])
        .arg(format!("{w}x{h}"))
        .args([
            "-framerate",
            &WEBP_FPS.to_string(),
            "-i",
            "-",
            "-c:v",
            "libwebp_anim",
            "-lossless",
            "0",
            "-quality",
            "70",
        ])
        .args(["-loop", "0", "-threads", "1", "-an"])
        .arg(out)
        .stdin(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("running ffmpeg for the WebP (it needs libwebp)")?;
    {
        let stdin = child.stdin.as_mut().context("ffmpeg stdin")?;
        for f in frames {
            stdin.write_all(f)?;
        }
    }
    let o = child.wait_with_output()?;
    if !o.status.success() {
        bail!("ffmpeg couldn't write the WebP: {}", String::from_utf8_lossy(&o.stderr).trim());
    }
    Ok(())
}
